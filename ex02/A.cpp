
#include <iostream>

#include "A.hpp"

///////////////////////////////////////////////////////////////////////////////
// Constructors / Destructor
///////////////////////////////////////////////////////////////////////////////

A::A()
{
    std::cout << "A Default constructor." << std::endl;
}

A::A(const A &a)
{
    *this = a;
    std::cout << "A Copy constructor." << std::endl;
}

A::~A()
{
    std::cout << "A destructor." << std::endl;
}

///////////////////////////////////////////////////////////////////////////////
// Operators
///////////////////////////////////////////////////////////////////////////////

A &A::operator=(const A &a)
{
    (void)a;
    std::cout << "A copy operator." << std::endl;

    return *this;
}

