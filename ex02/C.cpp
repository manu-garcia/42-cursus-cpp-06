
#include <iostream>

#include "C.hpp"

///////////////////////////////////////////////////////////////////////////////
// Constructors / Destructor
///////////////////////////////////////////////////////////////////////////////

C::C()
{
    std::cout << "C Default constructor." << std::endl;
}

C::C(const C &c)
{
    *this = c;
    std::cout << "C Copy constructor." << std::endl;
}

C::~C()
{
    std::cout << "C destructor." << std::endl;
}

///////////////////////////////////////////////////////////////////////////////
// Operators
///////////////////////////////////////////////////////////////////////////////

C &C::operator=(const C &c)
{
    (void)c;
    std::cout << "C copy operator." << std::endl;

    return *this;
}

